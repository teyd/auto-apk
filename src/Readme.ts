/**
 * The app table in README.md, generated from the config between two markers.
 * `bun src/main.ts readme` rewrites it; a test fails when it is stale.
 */
import { type Config, resolveApps } from "./Config.ts"
import { addLink, appEntry, microgEntry } from "./Obtainium.ts"

export const START = "<!-- apps:start (generated by `bun src/main.ts readme`; do not edit) -->"
export const END = "<!-- apps:end -->"

const BADGE = '<img src=".github/assets/obtainium-badge.png" alt="Add to Obtainium" height="40">'

export const appsTable = (config: Config): string => {
  const apps = resolveApps(config).filter((a) => a.enabled)
  const repo = config.publish.repo
  const rows = apps.map(
    (a) =>
      `| ${a.name} | \`${a.package}\` | [${a.patches.repo}](https://github.com/${a.patches.repo}) | [releases](https://github.com/${repo}/releases?q=${encodeURIComponent(`${a.id}-`)}&expanded=true) | [${BADGE}](${addLink(appEntry(config, a))}) |`,
  )
  const needsMicrog = apps.some((a) => a.package === "com.google.android.youtube")
  const arch = apps[0]?.arch ?? "arm64-v8a"
  return [
    "| App | Package | Patches | Builds | Install |",
    "|---|---|---|---|---|",
    ...rows,
    ...(needsMicrog
      ? [
          `| MicroG-RE (needed by YouTube) | \`app.revanced.android.gms\` | | [releases](https://github.com/MorpheApp/MicroG-RE/releases) | [${BADGE}](${addLink(microgEntry(arch))}) |`,
        ]
      : []),
  ].join("\n")
}

/** README with the table section replaced. Fails when the markers are missing. */
export const renderReadme = (readme: string, config: Config): string => {
  const start = readme.indexOf(START)
  const end = readme.indexOf(END)
  if (start < 0 || end < start) throw new Error(`README.md has no ${START} ... ${END} section`)
  return `${readme.slice(0, start + START.length)}\n\n${appsTable(config)}\n\n${readme.slice(end)}`
}
